-- Schema initial H2. Les migrations sont appliquees avant la validation Hibernate.
CREATE TABLE utilisateurs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(150) NOT NULL UNIQUE, nom VARCHAR(100) NOT NULL,
 telephone VARCHAR(30), departement VARCHAR(80) NOT NULL, version INTEGER NOT NULL
);
CREATE TABLE salles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nom VARCHAR(100) NOT NULL UNIQUE, capacite INTEGER NOT NULL CHECK (capacite > 0),
 batiment VARCHAR(80) NOT NULL, etage INTEGER NOT NULL,
 videoprojecteur BOOLEAN NOT NULL, accessiblePmr BOOLEAN NOT NULL,
 tarifHoraire NUMERIC(10,2) NOT NULL CHECK (tarifHoraire >= 0), version INTEGER NOT NULL
);
CREATE TABLE reservations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 salle_id BIGINT NOT NULL REFERENCES salles(id),
 utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
 dateDebut TIMESTAMP NOT NULL, dateFin TIMESTAMP NOT NULL,
 motif VARCHAR(150) NOT NULL, nombreParticipants INTEGER NOT NULL CHECK (nombreParticipants > 0),
 statut VARCHAR(20) NOT NULL CHECK (statut IN ('CONFIRMEE', 'ANNULEE')),
 version INTEGER NOT NULL, CHECK (dateFin > dateDebut)
);
